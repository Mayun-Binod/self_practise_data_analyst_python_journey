# Create a list of fruits and remove all items using clear().
fruits = ["apple", "banana", "orange", "mango"]
fruits.clear()
print(fruits)

# Create a list of numbers, print it, clear it, and print it again.
numbers = [10, 20, 30, 40, 50]
print(numbers)
numbers.clear()
print(numbers)

# Create a list of names and use clear() to make the list empty.
names = ["Ram", "Hari", "Sita", "Gita"]
names.clear()
print(names)


