# Create a list of numbers in random order and sort them in ascending order.
numbers = [50, 10, 40, 20, 30]
numbers.sort()
print(numbers)

# Create a list of numbers and sort them in descending order.
numbers = [50, 10, 40, 20, 30]
numbers.sort(reverse=True)
print(numbers)

# Create a list of names in random order and sort them alphabetically.
names = ["Shyam", "Ram", "Gita", "Hari", "Sita"]
names.sort()
print(names)

# Create a list of fruits and sort them alphabetically.
fruits = ["mango", "apple", "orange", "banana", "grapes"]
fruits.sort()
print(fruits)