# Create two lists of fruits and concatenate them using the + operator.
fruits1 = ["apple", "banana", "orange"]
fruits2 = ["mango", "grapes", "papaya"]
fruits = fruits1 + fruits2
print(fruits)

# Create two lists of numbers and join them into one list.
numbers1 = [10, 20, 30]
numbers2 = [40, 50, 60]
numbers = numbers1 + numbers2
print(numbers)

# Create three lists containing names and concatenate all three lists.
names1 = ["Ram", "Hari"]
names2 = ["Sita", "Gita"]
names3 = ["Shyam", "Mina"]
names = names1 + names2 + names3
print(names)

# Create a list containing strings and concatenate it with another list containing strings.
list1 = ["Python", "Java"]
list2 = ["sandhya", "prakriti"]
result = list1 + list2
print(result)

# Create two lists with different data types and concatenate them into one list.
list1 = ["Ram", 25, True]
