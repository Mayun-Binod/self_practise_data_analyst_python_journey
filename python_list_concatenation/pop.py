# Create a list of 6 fruits and use pop() to remove the last fruit.
fruits = ["apple", "banana", "orange", "mango", "grapes", "papaya"]
fruits.pop()
print(fruits)

# Create a list of numbers and use pop(2) to remove the item at index 2.
numbers = [10, 20, 30, 40, 50]
numbers.pop(2)
print(numbers)

# Create a list of names and remove the second-last name using pop().
names = ["Ram", "Hari", "Sita", "Gita", "Shyam"]
names.pop(-2)
print(names)

# Create a list of 7 numbers and remove two items using pop().
numbers = [10, 20, 30, 40, 50, 60, 70]
numbers.pop()
numbers.pop()
print(numbers)



