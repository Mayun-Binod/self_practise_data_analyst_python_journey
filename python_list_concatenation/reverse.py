# Create a list of numbers and reverse the list using reverse().
numbers = [10, 20, 30, 40, 50]
numbers.sort(reverse=True)
print(numbers)

# Create a list of names and reverse their order.
names = ["Ram", "Hari", "Sita", "Gita"]
names.reverse()
print(names)

# Create a list of fruits and print the original list, then reverse it and print it again.
fruits = ["apple", "banana", "orange", "mango"]
print(fruits)
fruits.reverse()
print(fruits)