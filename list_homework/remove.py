# Remove a specific fruit from a list.
fruits = ["apple", "banana", "mango", "orange"]
fruits.remove("mango")
print(fruits)

# Remove a specific number from a number list.
numbers = [10, 20, 30, 40]
numbers.remove(30)
print(numbers)

# Create a list with duplicate values and remove one occurrence using remove().
numbers = [10, 20, 10, 30, 10]
numbers.remove(10)
print(numbers)