# Remove the last item using pop().
fruits = ["apple", "banana", "mango", "orange"]
fruits.pop()
print(fruits)

# Remove the item at index 2 using pop().
fruits = ["apple", "banana", "mango", "orange"]
fruits.pop(2)
print(fruits)

# Use pop() twice and print the list after each operation.
numbers = [10, 20, 30, 40, 50]
numbers.pop()
print(numbers)
numbers.pop()
print(numbers)