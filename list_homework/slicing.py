# Print the first 3 items.
fruits = ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits[:3])

# Print the last 3 items.
fruits1 = ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits1[-3:])

# Print items from index 2 to 5.
fruits2= ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits2[2:5])

# Print every second item using slicing.
fruits3 = ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits3[::2])

# Reverse a list using slicing.
fruits4 = ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits4[::-1])

# Practice [::1], [::2], [::-1], and [::-2].
fruits5 = ["apple", "banana", "mango", "orange", "grapes", "kiwi"]
print(fruits5[::1])
print(fruits5[::2])
print(fruits5[::-1])
print(fruits5[::-2])