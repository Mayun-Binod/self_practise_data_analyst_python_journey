# Insert a new fruit at index 2.
fruits = ["apple", "banana", "mango", "orange"]
fruits.insert(2, "grapes")
print(fruits)

# Insert a number at the beginning of a number list.
numbers = [10, 20, 30, 40]
numbers.insert(0, 5)
print(numbers)

# Insert a name before the last item.
names = ["Ram", "Sita", "Hari", "Gita"]
names.insert(len(names) - 1, "Binod")
print(names)