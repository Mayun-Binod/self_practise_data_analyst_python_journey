# Create a tuple containing 5 fruits.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits)

# Access the first item of a tuple.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[0])

# Access the last item using negative indexing.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[-1])

# Slice a tuple to get the first 3 items.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[:3])

# Reverse a tuple using slicing.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[::-1])

# Find the length of a tuple using len().
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(len(fruits))

# Check whether a particular value exists using in.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print("apple" in fruits)

# Join two tuples using +.
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)
result = tuple1 + tuple2
print(result)

# Repeat a tuple three times using *.
numbers = (1, 2, 3)
result = numbers * 3
print(result)


