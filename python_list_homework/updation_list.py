# Create a list of 5 fruits and change the second fruit to "mango".
fruits = ["apple", "banana", "cherry", "orange", "kiwi"]
fruits[1] = "mango"
print(fruits)

# Create a list of 6 numbers and change the fourth number to 100.
numbers = [10, 20, 30, 40, 50, 60]
numbers[3] = 100
print(numbers)

# Create a list of 6 names and change the last name to "Binod".
