# Create a list of 7 fruits and change the third and fourth fruits using slicing.
fruits = ["apple", "banana", "cherry", "orange", "kiwi", "mango", "grape"]
fruits[2:4] = ["watermelon", "pineapple"]
print(fruits)

# Create a list of 6 numbers and replace the last two numbers with 50 and 60.
numbers = [10, 20, 30, 40, 70, 80]
numbers[-2:] = [50, 60]
print(numbers)



