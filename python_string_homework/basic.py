# Create a string in uppercase and convert it to lowercase using lower().
upper_string = "HELLO, WORLD!"
print(upper_string.lower())

# Create a string in lowercase and convert it to uppercase using upper().
lower_string = "hello, world!"
print(lower_string.upper())

# Create a sentence containing "Python" and replace "Python" with "Java" using replace().
text = "I am learning Python"
print(text.replace("Python", "Java"))

# Create a string with spaces at the beginning and end. Remove the spaces using strip().
text = "   Python java   "
print(text.strip())

# Create a sentence with several words and use split() to convert it into a list.
text = "Python is easy to learn"
print(text.split())

# Find the position of a specific word in a sentence using find().
text = "Python is easy to learn"
print(text.find("Python"))

# Count how many times "a" appears in a string using count().
text = "banana"
print(text.count("a"))

