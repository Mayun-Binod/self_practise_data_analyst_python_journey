# Create a tuple containing 5 fruits and print it.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits)

# Create a tuple containing different data types.
data = ("sandhya", 25, 3.37, True)
print(data)

# Access the first, middle, and last items of a tuple.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[0])
print(fruits[2])
print(fruits[-1])

# Access tuple items using negative indexing.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[-1])
print(fruits[-2])
print(fruits[-3])

# Slice a tuple to get the first 3 items.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[:3])

# Slice a tuple to get the last 3 items.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[-3:])

# Reverse a tuple using slicing.
fruits = ("apple", "banana", "mango", "orange", "grapes")
print(fruits[::-1])

