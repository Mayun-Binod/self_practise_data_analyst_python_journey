# Create a tuple with duplicate values and use count() to count one value.
numbers = (10, 20, 20, 30, 40)
print(numbers.count(20))

# Create a tuple and use index() to find the position of a value.
numbers = (10, 20, 30, 40, 50, 60)
print(numbers.index(50))

# Use len() to find the total number of items in a tuple.
numbers = (10, 20, 30, 40, 50)
print(len(numbers))

# Check whether a value exists in a tuple using in.
fruits = ("apple", "banana", "mango", "orange")
print("mango" in fruits)

# Concatenate two tuples using +.
tuple1 = (1, 2, 3)
tuple2 = (4, 5, 6)
result = tuple1 + tuple2
print(result)

# Repeat a tuple multiple times using the * operator.
numbers = (1, 2, 3)
result = numbers * 3
print(result)




